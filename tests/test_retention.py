def test_valid_llm_reply_is_used_and_priced_by_code():
    fake = FakeProvider(good_reply())
    offer = generate_offer(ROW, DRIVERS, 50.0, provider=fake)
    assert offer.generated_by == "LLM" and offer.badge == "Generated by: LLM (fake)"
    assert offer.actions[0]["id"] == "addon_tech_support"
    assert offer.total_cost == pytest.approx(30.0)  # code's price, not the model's
    assert offer.model == "fake-1" and offer.fallback_reason is None
    system, user = fake.calls[0]
    menu = json.loads(user)["menu"]
    assert any(m["id"] == "addon_tech_support" for m in menu)
    assert json.loads(user)["budget_usd"] == 50.0


