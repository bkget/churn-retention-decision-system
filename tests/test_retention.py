class FakeProvider:
    name = "fake"
    model = "fake-1"

    def __init__(self, reply=None, error=None, delay=0.0):
        self.reply, self.error, self.delay = reply, error, delay
        self.calls = []

    def generate(self, system, user):
        self.calls.append((system, user))
        if self.delay:
            import time

            time.sleep(self.delay)
        if self.error:
            raise self.error
        return self.reply if isinstance(self.reply, str) else json.dumps(self.reply)


def good_reply(ids=("addon_tech_support",), **over):
    base = {
        "action_ids": list(ids),
        "headline": "Free support trial",
        "customer_message": "Thanks for choosing us - enjoy 3 months of Premium Tech Support free.",
        "rep_notes": "Lead with the support trial.",
    }
    return base | over


