"""Headless smoke tests of the Streamlit app (Streamlit's AppTest; needs `make train` artifacts)."""

from __future__ import annotations

import pytest

pytest.importorskip("streamlit")
from streamlit.testing.v1 import AppTest  # noqa: E402

from src.config import load_settings, resolve  # noqa: E402

_ARTIFACT = resolve(load_settings()["paths"]["scored_file"])
pytestmark = pytest.mark.skipif(not _ARTIFACT.exists(), reason="run `make train` first")


@pytest.fixture
def app(monkeypatch):
    for var in ("LLM_PROVIDER", "GEMINI_API_KEY", "OPENAI_API_KEY", "ANTHROPIC_API_KEY"):
        monkeypatch.delenv(var, raising=False)
    # keep .env from the developer's machine out of the test
    monkeypatch.setattr("dotenv.load_dotenv", lambda *a, **k: False, raising=False)
    at = AppTest.from_file(str(resolve("app.py")), default_timeout=90)
    at.run()
    return at


def _metric(at, label):
    return next(m for m in at.metric if m.label == label)


def test_app_renders_three_tabs_without_errors(app):
    assert not app.exception
    labels = [t.label for t in app.tabs]
    for expected in ("Executive Overview", "ROI Simulator", "At-Risk Account Explorer"):
        assert expected in labels
    assert labels.index("Executive Overview") < labels.index("ROI Simulator")
    assert labels.index("ROI Simulator") < labels.index("At-Risk Account Explorer")


def test_overview_kpis_present(app):
    labels = {m.label for m in app.metric}
    assert {"Customers", "Churn rate", "Revenue at risk", "Model PR-AUC (test)"} <= labels
    assert _metric(app, "Customers").value == "7,043"


def test_roi_sliders_update_threshold_targets_and_net(app):
    base_t = _metric(app, "Optimal threshold").value
    base_net = _metric(app, "Net $ saved").value
    base_n = _metric(app, "Customers to target").value

    app.slider(key="offer_cost").set_value(150).run()
    assert not app.exception
    assert _metric(app, "Optimal threshold").value != base_t
    assert _metric(app, "Net $ saved").value != base_net
    assert _metric(app, "Customers to target").value != base_n

    # a higher offer cost can only shrink the campaign
    n_high = int(_metric(app, "Customers to target").value.replace(",", ""))
    assert n_high <= int(base_n.replace(",", ""))


def test_unprofitable_campaign_shows_warning_and_no_targets(app):
    app.slider(key="offer_cost").set_value(300).run()
    app.slider(key="acceptance").set_value(2).run()
    assert not app.exception
    assert _metric(app, "Optimal threshold").value == "no campaign"
    assert _metric(app, "Customers to target").value == "0"
    assert any("No threshold earns" in w.value for w in app.warning)


def test_explorer_generates_template_offer_without_api_key(app):
    app.button(key="gen_offer").click().run()
    assert not app.exception
    text = " ".join(m.value for m in app.markdown)
    assert "Generated by: Template" in text
    assert any("deterministic template engine" in i.value for i in app.info)


def test_explorer_shows_only_current_subscribers_by_default(app):
    assert app.checkbox(key="f_churned").value is False
    app.checkbox(key="f_churned").set_value(True).run()
    assert not app.exception
